create table if not exists public."CustomLinks" (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public."Users_Info"(id) on delete cascade,
  title text not null,
  description text not null default '',
  url text not null,
  category text not null default 'Custom',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists custom_links_user_updated_idx
  on public."CustomLinks"(user_id, updated_at desc);

alter table public."CustomLinks" enable row level security;

drop policy if exists "CustomLinks select own rows" on public."CustomLinks";
create policy "CustomLinks select own rows"
  on public."CustomLinks"
  for select
  to authenticated
  using (
    user_id in (
      select id
      from public."Users_Info"
      where auth_user_id = auth.uid()
    )
  );

drop policy if exists "CustomLinks insert own rows" on public."CustomLinks";
create policy "CustomLinks insert own rows"
  on public."CustomLinks"
  for insert
  to authenticated
  with check (
    user_id in (
      select id
      from public."Users_Info"
      where auth_user_id = auth.uid()
    )
  );

drop policy if exists "CustomLinks update own rows" on public."CustomLinks";
create policy "CustomLinks update own rows"
  on public."CustomLinks"
  for update
  to authenticated
  using (
    user_id in (
      select id
      from public."Users_Info"
      where auth_user_id = auth.uid()
    )
  )
  with check (
    user_id in (
      select id
      from public."Users_Info"
      where auth_user_id = auth.uid()
    )
  );

drop policy if exists "CustomLinks delete own rows" on public."CustomLinks";
create policy "CustomLinks delete own rows"
  on public."CustomLinks"
  for delete
  to authenticated
  using (
    user_id in (
      select id
      from public."Users_Info"
      where auth_user_id = auth.uid()
    )
  );


