create table if not exists public."Exams" (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public."Users_Info"(id) on delete cascade,
  subject text not null,
  exam_date date not null,
  results_date date,
  result_value text,
  result_status text,
  study_resources jsonb not null default '[]'::jsonb,
  exam_date_reminder_sent_at timestamptz,
  results_date_reminder_sent_at timestamptz,
  generated_checklist_todo_id bigint references public."ToDoItems"(id) on delete set null,
  linked_grade_id bigint references public."EducationGrades"(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists exams_user_exam_date_idx on public."Exams"(user_id, exam_date);

create table if not exists public."RecurringTransactions" (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public."Users_Info"(id) on delete cascade,
  type text not null check (type in ('Income', 'Expense')),
  title text not null,
  description text not null default '',
  category_id bigint references public."TransactionCategories"(id) on delete set null,
  amount numeric not null check (amount >= 0),
  frequency text not null check (frequency in ('weekly', 'monthly')),
  start_date date not null,
  next_due_date date not null,
  end_date date,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists recurring_transactions_user_active_idx on public."RecurringTransactions"(user_id, is_active, next_due_date);

alter table public."Transactions"
  add column if not exists recurring_transaction_id bigint references public."RecurringTransactions"(id) on delete set null,
  add column if not exists recurrence_due_date date;
create unique index if not exists transactions_recurring_due_unique on public."Transactions"(recurring_transaction_id, recurrence_due_date)
  where recurring_transaction_id is not null and recurrence_due_date is not null;

alter table public."Exams" enable row level security;
alter table public."RecurringTransactions" enable row level security;
drop policy if exists "Exams own rows" on public."Exams";
create policy "Exams own rows" on public."Exams" for all to authenticated
  using (user_id in (select id from public."Users_Info" where auth_user_id = auth.uid()))
  with check (user_id in (select id from public."Users_Info" where auth_user_id = auth.uid()));
drop policy if exists "RecurringTransactions own rows" on public."RecurringTransactions";
create policy "RecurringTransactions own rows" on public."RecurringTransactions" for all to authenticated
  using (user_id in (select id from public."Users_Info" where auth_user_id = auth.uid()))
  with check (user_id in (select id from public."Users_Info" where auth_user_id = auth.uid()));
grant select, insert, update, delete on public."Exams" to authenticated;
grant select, insert, update, delete on public."RecurringTransactions" to authenticated;


