alter table public."ToDoItems"
  add column if not exists item_kind text not null default 'task';

alter table public."ToDoItems"
  drop constraint if exists todoitems_item_kind_check;

alter table public."ToDoItems"
  add constraint todoitems_item_kind_check
  check (item_kind in ('task', 'checklist'));

create table if not exists public."ToDoChecklistItems" (
  id bigint generated by default as identity primary key,
  todo_id bigint not null references public."ToDoItems"(id) on delete cascade,
  user_id bigint not null references public."Users_Info"(id) on delete cascade,
  text text not null,
  is_complete boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists todo_checklist_items_todo_position_idx
  on public."ToDoChecklistItems" (todo_id, position);


